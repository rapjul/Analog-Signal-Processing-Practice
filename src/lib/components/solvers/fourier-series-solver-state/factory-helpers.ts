/**
 * Fourier Series Step Solver Multi-Part State Factory Helpers.
 *
 * Provides factory initializers for coefficient sub-steps and symmetry sub-steps.
 */

import {
	createMultiPartStepState,
	createSubStepState,
} from "$lib/components/solvers/base-step-solver.svelte";
import type {
	FourierCoefficientPart,
	FourierItsStep2,
	OriginParity,
} from "$lib/math-engine/fourier-series/index";
import type {
	FourierCoefficientMultiPartState,
	FourierCoefficientSubStepState,
	FourierSeriesSymmetrySubStepId,
	FourierSymmetryStepState,
} from "./fourier-series-step-types";

/**
 * Creates multi-part state for the ordered coefficient parts generated by the Fourier Series engine.
 *
 * @param {FourierCoefficientPart[]} parts - Ordered coefficient evaluation parts (e.g. a0, an, bn).
 * @returns {FourierCoefficientMultiPartState} Initialized multi-part step state.
 */
export function createCoefficientMultiPartState(
	parts: FourierCoefficientPart[],
): FourierCoefficientMultiPartState {
	const normalizedParts =
		parts.length > 0
			? parts
			: [
					{
						id: "placeholder",
						target: "a0",
						title: "Coefficient",
						prompt: "",
						resultLatex: "",
						options: [],
						hints: [],
					} satisfies FourierCoefficientPart,
				];
	const order = normalizedParts.map(({ id }) => id);
	const subSteps = Object.fromEntries(
		normalizedParts.map((part) => [
			part.id,
			createSubStepState(
				part.id,
				part.title,
				{ selected: null as string | null },
				part.hints,
			),
		]),
	) as Record<string, FourierCoefficientSubStepState>;
	return createMultiPartStepState(
		{},
		order,
		subSteps,
		order[0] ?? "",
	) as FourierCoefficientMultiPartState;
}

/**
 * Creates the two focused symmetry sub-steps (origin parity and half-wave) and their independent hints.
 *
 * @param {FourierItsStep2} data - Step 2 ITS scaffolding metadata.
 * @returns {FourierSymmetryStepState} Initialized symmetry step state.
 */
export function createSymmetryMultiPartState(
	data: FourierItsStep2,
): FourierSymmetryStepState {
	const subStepOrder: FourierSeriesSymmetrySubStepId[] = [
		"origin-parity",
		"half-wave",
	];
	return createMultiPartStepState(
		{},
		subStepOrder,
		{
			"origin-parity": createSubStepState(
				"origin-parity",
				"Classify Origin Parity",
				{ selected: null as OriginParity | null },
				data.hints,
			),
			"half-wave": createSubStepState(
				"half-wave",
				"Test Half-Wave Symmetry",
				{ selected: null as boolean | null },
				data.halfWaveHints,
			),
		},
		"origin-parity",
	) as FourierSymmetryStepState;
}
